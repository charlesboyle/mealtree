/**
 * Arabic count phrases: forms for 1, 2, 3–10, 11–99 and the rest.
 * e.g. طبق واحد · طبقان · 5 أطباق · 12 طبقًا · 100 طبق
 */
function count(n: number, forms: { one: string; two: string; few: string; many: string; other: string }) {
  const mod = n % 100;
  if (n === 1) return forms.one;
  if (n === 2) return forms.two;
  if (mod >= 3 && mod <= 10) return `${n} ${forms.few}`;
  if (mod >= 11 && mod <= 99) return `${n} ${forms.many}`;
  return `${n} ${forms.other}`;
}

